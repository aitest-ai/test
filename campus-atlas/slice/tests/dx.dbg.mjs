import fs from 'fs';
import { buildModel } from '../src/dongxin/model.js';
import { createDxWorld } from '../src/dongxin/world.js';
import { createDxNav } from '../src/dongxin/nav.js';
import { createWalker } from '../src/nav/navgraph.js';
const D = JSON.parse(fs.readFileSync(new URL('../data/dongxin_geo.json', import.meta.url)));
const m = buildModel(D), world = createDxWorld(m), nav = createDxNav(m, world);
const [,, from, to] = process.argv;
const find = (n) => [...m.ROOMS, ...m.PLACES].find(r => r.name === n);
const a = find(from), b = find(to);
const rt = nav.route({ x: a.x, z: a.z, y: m.LY(a.f) }, b);
console.log('route pts', rt.pts.length, rt.pts.map(p => `(${p.x.toFixed(1)},${p.z.toFixed(1)},${p.y.toFixed(1)}${p.stair ? 's' : ''})`).join(' '));
const w = createWalker(world, rt, { tol: 0.12 }), p = { x: a.x, z: a.z, y: m.LY(a.f), heading: 0 };
for (let t = 0; t < 200 && !w.done && !w.stuck; t += 1 / 30) w.step(p, 1 / 30, 6);
console.log('end', p, w.done, w.stuck);
const s = m.STAIRS.find(s => world.stairAt(p.x, p.z, 1)); if (s) console.log('near stair', s.id, s.along, s.sgn, 'uA', s.uA, 'uB', s.uB, 'lane', s.lane, 'ww', s.ww, 'sh', s.sh, 'ent', s.ent);
console.log('hit here', !!world.hit(p.x, p.z, p.y, 0.3), 'surf', world.surfaces(p.x, p.z));
const i = Math.floor((p.x - m.WX0) / m.CELL), j = Math.floor((p.z - m.WZ0) / m.CELL);
for (let dj = -3; dj <= 3; dj++) console.log((j + dj) + ' ' + Array.from({ length: 13 }, (_, k) => { const q = (j + dj) * m.GW + i - 6 + k; return m.ERO[0][q] ? 'E' : m.NAV[0][q] ? 'n' : (m.RC[0][q] >= 0 ? 'r' : '#'); }).join(''));
console.log('next pt', rt.pts[2], 'p cell', i, j);
